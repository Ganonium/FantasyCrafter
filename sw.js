// Service Worker: macht das Spiel offline startbar und installierbar.
// Strategie „Netz zuerst“, damit neue Versionen sofort ankommen; Cache nur als Rückfall.
// cache: 'no-cache' fragt immer beim Server nach (GitHub Pages erlaubt sonst bis zu 10 Min. alte Dateien).
const CACHE = 'fantasycrafter-v2';

self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (e) => e.waitUntil(
  caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()),
));

self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(
    fetch(e.request, { cache: 'no-cache' })
      .then((res) => {
        const copy = res.clone();
        caches.open(CACHE).then((c) => c.put(e.request, copy));
        return res;
      })
      .catch(() => caches.match(e.request, { ignoreSearch: true })),
  );
});
